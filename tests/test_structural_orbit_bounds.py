"""Mathematical upper-bound regressions independent from any search engine."""
import pytest
from math import comb
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from structural_orbit_bounds import coefficient, all_coefficients


def test_exact_d4_all_25_occupancies():
    result = all_coefficients()
    assert result["total_structural_orbits"] == 211836900942
    assert sum(result["by_occupancy"].values()) == 211836900942
    assert [coefficient(k) for k in range(9)] == [
        2, 24, 366, 4892, 51732, 428616, 2843800, 15407920, 69278970
    ]


def test_observed_5x5_reachability_below_proved_structural_upper():
    # Purely independently derived counts, not generated by the code under test.
    reachable_orbits = (1, 3, 60, 1512, 23659, 258081, 2048650, 12475164, 60627546)
    for k, observed in enumerate(reachable_orbits):
        assert 0 < observed <= coefficient(k)


def test_burnside_base_and_invalid_input():
    assert coefficient(0) == 2  # two possible turns; actual X-first empty only one
    for bad in (-1, 26, True, 1.0):
        with pytest.raises(ValueError):
            coefficient(bad)
